const tid = () => `t${++seq}`;

const item = (
  typeId: string,
  start: Minutes,
  duration: number,
  extra: Partial<TemplateItem> = {},
): TemplateItem => ({ id: tid(), typeId, start, duration, days: EVERY_DAY, ...extra });

